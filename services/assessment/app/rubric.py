async def seed(session: AsyncSession, subjects: list[dict]) -> int:
    """Создать разделы и темы для известных предметов. Возвращает число созданных тем."""
    created = 0
    for subject in subjects:
        sections = DEFAULT_TOPICS.get(subject["name"])
        for i, (section_title, topics) in enumerate((sections or {}).items()):
            section = Topic(subject_id=subject["id"], subject_name=subject["name"], title=section_title, position=i)
            session.add(section)
            await session.flush()
            for j, title in enumerate(topics):
                session.add(Topic(subject_id=subject["id"], subject_name=subject["name"], parent_id=section.id, title=title, position=j))
            created += 1 + len(topics)
    return created


def seed_exams(session: AsyncSession, subjects: list[dict]) -> int:
    """Создать экзамены ЕГЭ/ОГЭ и их задания для известных предметов. Возвращает число экзаменов."""
    created = 0
    for subject in subjects:
        for kind, title, items in DEFAULT_EXAMS.get(subject["name"], []):
            session.add(Exam(
                kind=kind, subject_id=subject["id"], subject_name=subject["name"], title=title, position=created,
                items=[ExamItem(number=n, title=t) for n, t in enumerate(items, start=1)],
            ))
            created += 1
    return created


async def ensure_default_topics() -> None:
    """Фоновая задача: заполнить пустые рубрикатор и каталог ЕГЭ/ОГЭ
    (content может запуститься позже — тогда попробуем снова)."""
    async with db.sessionmaker() as session, session.begin():
        # Несколько экземпляров сервиса не должны заполнить справочники дважды.
        await session.execute(text("SELECT pg_advisory_xact_lock(hashtext('assessment.topics.seed'))"))
        need_topics = not await session.scalar(select(func.count()).select_from(Topic))
        need_exams = not await session.scalar(select(func.count()).select_from(Exam))
        if not (need_topics or need_exams):
            return
        subjects = await content.get("/subjects")
        if need_topics:
            log.info("default topics created", extra={"count": await seed(session, subjects)})
        if need_exams:
            log.info("default exams created", extra={"count": seed_exams(session, subjects)})
